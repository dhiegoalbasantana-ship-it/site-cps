CREATE TABLE IF NOT EXISTS agendamentos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
  nome TEXT NOT NULL,
  telefone TEXT NOT NULL,
  tipo_servico TEXT,
  periodo TEXT,
  mensagem TEXT,
  origem TEXT DEFAULT 'Portal Web CPS'
);

-- Ativar Row Level Security (RLS)
ALTER TABLE agendamentos ENABLE ROW LEVEL SECURITY;

-- Política para permitir que o site envie os agendamentos:
DROP POLICY IF EXISTS "Permitir criacao anonima de agendamentos" ON agendamentos;
CREATE POLICY "Permitir criacao anonima de agendamentos" 
ON agendamentos 
FOR INSERT 
TO anon 
WITH CHECK (true);

-- Política para você visualizar os agendamentos:
DROP POLICY IF EXISTS "Permitir leitura de agendamentos" ON agendamentos;
CREATE POLICY "Permitir leitura de agendamentos" 
ON agendamentos 
FOR SELECT 
TO anon 
USING (true);
